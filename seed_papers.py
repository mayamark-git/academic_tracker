def seed_database():
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    # テーブル作成
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS papers (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        title TEXT UNIQUE,
        author TEXT,
        journal TEXT,
        pub_date TEXT,
        doi TEXT,
        url TEXT,
        abstract TEXT,
        ai_insight TEXT,
        priority TEXT,
        suggested_section TEXT,
        draft_text TEXT,
        is_read INTEGER DEFAULT 0,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
    """)

    # 既存データを一旦全件削除して綺麗なマスターを投入
    cursor.execute("DELETE FROM papers")

    for p in PAPERS_DATA:
        cursor.execute("""
            INSERT INTO papers 
            (title, author, journal, pub_date, doi, url, abstract, ai_insight, priority, suggested_section, draft_text)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, p)

    conn.commit()
    conn.close()
    print(f"✨ 成功! {len(PAPERS_DATA)} 件の重要論文をデータベースに書き込みました。")

